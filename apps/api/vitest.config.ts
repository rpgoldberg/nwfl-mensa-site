import { defineConfig } from 'vitest/config';

// The coverage gate lives here, not only in CI, so `npm run test:coverage`
// fails locally on the same thresholds: 85 % line AND branch, PER FILE, so an
// untested file cannot hide behind well-covered neighbours.
export default defineConfig({
  test: {
    environment: 'node',
    include: ['src/**/*.test.ts', 'test/**/*.test.ts'],
    exclude: ['node_modules', 'dist'],
    testTimeout: 30_000,
    hookTimeout: 60_000,
    coverage: {
      provider: 'v8',
      reporter: ['text', 'lcov'],
      include: ['src'],
      exclude: [
        'src/**/*.test.ts',
        // Generated by protoc-gen-es from proto/; checked by the CI diff step.
        'src/gen/**',
        // The process entrypoint: env reads, listen and signal wiring only.
        // Everything it calls is covered through startServer().
        'src/main.ts',
        // The seed command's entrypoint: argv, env and stdout only (seed.ts is tested).
        'src/seed/cli.ts',
      ],
      thresholds: {
        perFile: true,
        lines: 85,
        branches: 85,
        functions: 85,
        statements: 85,
      },
    },
  },
});
